import type { OrderStatus } from '../../lib/types'

/**
 * 订单状态饼图的专用配色。
 *
 * 这里原本直接复用 StatusChip 的 `ORDER_TONE`，结果是饼图上六个扇区只有四种颜色：
 * 「待审核」和「部分发货」同为 warn（同一个橙），「已发货」和「已完成」同为 ok（同一个绿）。
 * 在状态标签上这没问题——每个标签旁边都写着字，颜色只是辅助；到了饼图上颜色**就是**信息，
 * 两块一模一样的橙贴在一起，看的人分不出哪块是哪块，图例也对不上号。
 *
 * 所以饼图单独排一套色：按订单生命周期从暖到冷走一遍，六个状态六个色，语义方向仍然保留
 * （待办=暖色、在途=蓝紫、完成=绿、作废=灰）。相邻两段刻意跨色相而不是只调深浅——
 * 同色系深浅在投影仪上基本等于同一个颜色，而这套图是给面试现场的投影看的。
 */
export const ORDER_SLICE_HEX: Record<OrderStatus, string> = {
  待审核: '#fdab3d',   // 橙：等人动手
  待发货: '#0073ea',   // 蓝：已确认待执行
  部分发货: '#a25ddc', // 紫：执行中
  已发货: '#00c875',   // 绿：已交付
  已完成: '#037f4c',   // 深绿：已闭环
  已取消: '#c4c4c4',   // 灰：作废
}

/** 取扇区色。种子里不会出现表外状态，但真接了外部数据就会——落到灰色比崩掉好。 */
export function sliceColor(status: string): string {
  return ORDER_SLICE_HEX[status as OrderStatus] ?? '#c4c4c4'
}
